"""Write the TikZ figure of Phase 1 (threshold against batch size) from a Phase 1 raw file.

In the public repository the raw file is evidence/mean-square-boundary/raw-phase1.json (Phase 9 of the companion lab). P = 64, i.i.d. Gaussian and Rademacher features, beta in {0, 0.9},
B in {4, 16, 64}: the one-dimensional ceiling along u_1, the secular root of Theorem G and the median sample-path ceiling
(with its 5-95 % range over seeds), on log axes. Every plotted number is read from the raw file.

Usage: python3 make-fig-phase1.py <raw-phase1.json> <out.tex>
"""
import json
import math
import sys

raw_path, out_path = sys.argv[1], sys.argv[2]
cells = json.load(open(raw_path, encoding="utf-8"))["cells"]
BS = (4, 16, 64)
FAM = (("gaussian-iid", "gauss", "Gaussian"), ("rademacher-iid", "radem", "Rademacher"))
YMIN, YMAX = 0.03, 5.0
W, H = 5.6, 5.0


def cell(beta, b, fam):
    hit = [c for c in cells if c["numParams"] == 64 and c["beta"] == beta and c["batchB"] == b and c["featureFamily"] == fam]
    if len(hit) != 1:
        raise SystemExit(f"expected one cell P=64 beta={beta} B={b} {fam}, found {len(hit)}")
    return hit[0]


def xy(b, eta, x0):
    x = x0 + W * (math.log2(b) - 2.0) / 4.0
    y = H * (math.log10(eta) - math.log10(YMIN)) / (math.log10(YMAX) - math.log10(YMIN))
    return f"({x:.4f},{y:.4f})"


out = [f"% Generated by paper/figures/make-fig-phase1.py from {raw_path}; do not edit.",
       "\\begin{tikzpicture}[font=\\footnotesize]",
       "\\tikzset{gauss/.style={blue!70!black}, radem/.style={orange!85!black}}"]
for panel, beta in enumerate((0.0, 0.9)):
    x0 = panel * (W + 1.6)
    out.append(f"\\draw ({x0},0) rectangle ({x0 + W},{H});")
    for b in BS:
        x = x0 + W * (math.log2(b) - 2.0) / 4.0
        out.append(f"\\draw ({x:.4f},0) -- ({x:.4f},-0.08) node[below] {{{b}}};")
    for tick in (0.03, 0.1, 0.3, 1.0, 3.0):
        y = H * (math.log10(tick) - math.log10(YMIN)) / (math.log10(YMAX) - math.log10(YMIN))
        out.append(f"\\draw[gray!25] ({x0},{y:.4f}) -- ({x0 + W},{y:.4f});")
        out.append(f"\\draw ({x0},{y:.4f}) -- ({x0 - 0.08},{y:.4f}) node[left] {{{tick:g}}};")
    out.append(f"\\node at ({x0 + W / 2},-0.75) {{batch size $B$}};")
    out.append(f"\\node[anchor=south] at ({x0 + W / 2},{H + 0.05}) {{$P=64$, $\\beta={beta:g}$}};")
    if panel == 0:
        out.append(f"\\node[rotate=90] at ({x0 - 1.05},{H / 2}) {{learning rate $\\eta$}};")
    for fam, sty, _ in FAM:
        rows = [cell(beta, b, fam) for b in BS]
        one = " -- ".join(xy(b, r["etaCritOneDim"], x0) for b, r in zip(BS, rows))
        sec = " -- ".join(xy(b, r["etaCritSecular"], x0) for b, r in zip(BS, rows))
        out.append(f"\\draw[{sty}, dashed, thick] {one};")
        out.append(f"\\draw[{sty}, thick] {sec};")
        for b, r in zip(BS, rows):
            out.append(f"\\draw[{sty}] {xy(b, r['empiricalCeilingP05'], x0)} -- {xy(b, r['empiricalCeilingP95'], x0)};")
            out.append(f"\\fill[{sty}] {xy(b, r['empiricalCeilingMedian'], x0)} circle (1.6pt);")
lx = 2 * W + 1.6 + 0.4
legend = [("gauss", "thick", "secular root, Gaussian"), ("radem", "thick", "secular root, Rademacher"),
          ("gauss", "dashed, thick", "1D ceiling, Gaussian"), ("radem", "dashed, thick", "1D ceiling, Rademacher")]
for i, (sty, line, text) in enumerate(legend):
    y = H - 0.4 - 0.45 * i
    out.append(f"\\draw[{sty}, {line}] ({lx},{y}) -- ({lx + 0.6},{y}) node[right, black] {{{text}}};")
y = H - 0.4 - 0.45 * len(legend)
out.append(f"\\fill[gauss] ({lx + 0.15},{y}) circle (1.6pt); \\fill[radem] ({lx + 0.45},{y}) circle (1.6pt);")
out.append(f"\\node[right] at ({lx + 0.6},{y}) {{sample paths (median, 5--95\\,\\%)}};")
out.append("\\end{tikzpicture}")
open(out_path, "w", encoding="utf-8").write("\n".join(out) + "\n")
print("written", len(out), "lines")
