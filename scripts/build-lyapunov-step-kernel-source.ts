/**
 * @file scripts/build-lyapunov-step-kernel-source.ts
 * @description Source text of the lockstep linearised heavy-ball step for `G` step sizes on the row-major pair layout
 * (`buildLyapunovStepKernelSource`), written to `labs/mean-square-boundary/step-eigenbasis-lyapunov-g<G>.gen.ts` by
 * `scripts/generate-lyapunov-step-kernels.ts`. The kernel is `stepEigenbasisLyapunovGeneral` with the loop over the `G`
 * states unrolled inside the row loop (each minibatch entry is loaded once for the `G` states) and the per-state operations
 * unchanged, so every state is bit-identical to the general kernel and to `simulateEigenbasisLyapunovExponentReference`.
 * @cold
 */
const range = (g: number): number[] => Array.from({ length: g }, (_, i) => i);
const off = (i: number, v: string): string => (i === 0 ? v : `(o${i} + ${v}) | 0`);

function header(g: number): string[] {
  return [
    '/**',
    ` * @file labs/mean-square-boundary/step-eigenbasis-lyapunov-g${g}.gen.ts`,
    ` * @description Generated by \`scripts/generate-lyapunov-step-kernels.ts\` (do not edit): one renormalised linearised`,
    ` * heavy-ball step for ${g} step size${g > 1 ? 's' : ''} sharing one scaled minibatch deviation, on the row-major pair layout`,
    ` * (\`stepEigenbasisLyapunovG${g}\`). Same operations per state as \`stepEigenbasisLyapunovGeneral\`; \`x\`, \`xPrev\`, \`r\` hold the`,
    ' * states one after the other (`n` entries each).',
    ' * @cold',
    ' */',
    "import { fdlibmLog } from '../../src/math/index.ts';",
    '',
    `export function stepEigenbasisLyapunovG${g}(`,
    '  sum: Float64Array,',
    '  curvature: Float64Array,',
    '  x: Float64Array,',
    '  xPrev: Float64Array,',
    '  r: Float64Array,',
    '  n: number,',
    '  beta: number,',
    '  etas: Float64Array,',
    '  logs: Float64Array,',
    '  recordLog: boolean,',
    '): void {',
    ...range(g).filter((i) => i > 0).map((i) => `  const o${i} = Math.imul(${i}, n);`),
    ...range(g).map((i) => `  const eta${i} = etas[${i}]!;`),
  ];
}

function product(g: number): string[] {
  return [
    '  for (let a = 0; a < n; (a = (a + 1) | 0)) {',
    '    const ca = curvature[a]!;',
    ...range(g).map((i) => `    r[${off(i, 'a')}] = ca * x[${off(i, 'a')}]!;`),
    '  }',
    '  let p = 0;',
    '  for (let a = 0; a < n; (a = (a + 1) | 0)) {',
    '    const vd = sum[p]!;',
    '    p = (p + 1) | 0;',
    ...range(g).map((i) => `    const xa${i} = x[${off(i, 'a')}]!;`),
    ...range(g).map((i) => `    let ra${i} = r[${off(i, 'a')}]! + vd * xa${i};`),
    '    for (let c = (a + 1) | 0; c < n; (c = (c + 1) | 0)) {',
    '      const v = sum[p]!;',
    '      p = (p + 1) | 0;',
    ...range(g).flatMap((i) => [`      ra${i} += v * x[${off(i, 'c')}]!;`, `      r[${off(i, 'c')}] = r[${off(i, 'c')}]! + v * xa${i};`]),
    '    }',
    ...range(g).map((i) => `    r[${off(i, 'a')}] = ra${i};`),
    '  }',
  ];
}

function update(g: number): string[] {
  return [
    ...range(g).map((i) => `  let nrm${i} = 0.0;`),
    '  for (let k = 0; k < n; (k = (k + 1) | 0)) {',
    ...range(g).flatMap((i) => [
      `    const k${i} = ${off(i, 'k')};`,
      `    const cur${i} = x[k${i}]!;`,
      `    const next${i} = cur${i} + beta * (cur${i} - xPrev[k${i}]!) - eta${i} * r[k${i}]!;`,
      `    xPrev[k${i}] = cur${i};`,
      `    x[k${i}] = next${i};`,
      `    nrm${i} += next${i} * next${i} + cur${i} * cur${i};`,
    ]),
    '  }',
    ...range(g).map((i) => `  const nu${i} = Math.sqrt(nrm${i});`),
    '  if (recordLog) {',
    ...range(g).map((i) => `    logs[${i}] = logs[${i}]! + fdlibmLog(nu${i});`),
    '  }',
    ...range(g).map((i) => `  const inv${i} = 1.0 / nu${i};`),
    '  for (let k = 0; k < n; (k = (k + 1) | 0)) {',
    ...range(g).flatMap((i) => [`    const k${i} = ${off(i, 'k')};`, `    x[k${i}] = x[k${i}]! * inv${i};`, `    xPrev[k${i}] = xPrev[k${i}]! * inv${i};`]),
    '  }',
    '}',
    '',
  ];
}

export function buildLyapunovStepKernelSource(g: number): string {
  return [...header(g), ...product(g), ...update(g)].join('\n');
}
